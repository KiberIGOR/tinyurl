// Утилита генерации методов Reset() для структур с пометкой // generate:reset.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"strings"

	"golang.org/x/tools/go/packages"
)

const marker = "generate:reset"

type resetJob struct {
	dir   string
	name  string
	named *types.Named
}

func main() {
	root := flag.String("root", ".", "корень модуля для сканирования")
	flag.Parse()

	absRoot, err := filepath.Abs(*root)
	if err != nil {
		log.Fatal(err)
	}

	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedModule,
		Dir:  absRoot,
	}

	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		log.Fatal(err)
	}

	jobsByDir := make(map[string][]resetJob)

	for _, pkg := range pkgs {
		if pkg.IllTyped || len(pkg.Errors) > 0 {
			for _, e := range pkg.Errors {
				log.Println("skip package:", e)
			}
			continue
		}
		if shouldSkipPackage(pkg) {
			continue
		}

		for i, file := range pkg.Syntax {
			if i < len(pkg.GoFiles) {
				base := filepath.Base(pkg.GoFiles[i])
				if strings.HasSuffix(base, "_test.go") || base == "reset.gen.go" {
					continue
				}
			}
			_ = file
			for _, decl := range file.Decls {
				gen, ok := decl.(*ast.GenDecl)
				if !ok || gen.Tok != token.TYPE {
					continue
				}
				for _, spec := range gen.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok || !isStructType(ts, pkg.TypesInfo) {
						continue
					}
					if !hasMarker(gen.Doc) && !hasMarker(ts.Doc) {
						continue
					}
					name := ts.Name.Name
					obj := pkg.TypesInfo.Defs[ts.Name]
					if obj == nil {
						continue
					}
					named, ok := obj.Type().(*types.Named)
					if !ok {
						continue
					}
					dir := filepath.Dir(pkg.GoFiles[0])
					jobsByDir[dir] = append(jobsByDir[dir], resetJob{dir: dir, name: name, named: named})
				}
			}
		}
	}

	for dir, jobs := range jobsByDir {
		if err := writeResetFile(dir, jobs); err != nil {
			log.Fatal(err)
		}
		fmt.Println("wrote", filepath.Join(dir, "reset.gen.go"))
	}
}

func shouldSkipPackage(pkg *packages.Package) bool {
	if pkg.PkgPath == "github.com/KiberIGOR/tinyurl/cmd/reset" {
		return true
	}
	return strings.HasSuffix(pkg.PkgPath, "/vendor") || pkg.Name == "main" && strings.Contains(pkg.PkgPath, "/cmd/reset")
}

func isStructType(ts *ast.TypeSpec, info *types.Info) bool {
	t := info.TypeOf(ts.Type)
	if t == nil {
		return false
	}
	_, ok := types.Unalias(t).Underlying().(*types.Struct)
	return ok
}

func hasMarker(doc *ast.CommentGroup) bool {
	if doc == nil {
		return false
	}
	for _, c := range doc.List {
		line := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if line == marker {
			return true
		}
	}
	return false
}

func writeResetFile(dir string, jobs []resetJob) error {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/reset; DO NOT EDIT.\n\n")
	buf.WriteString("package ")
	buf.WriteString(jobs[0].named.Obj().Pkg().Name())
	buf.WriteString("\n\n")

	for _, j := range jobs {
		writeResetMethod(&buf, j.named, j.named.Obj().Pkg())
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\n%s", err, buf.String())
	}

	out := filepath.Join(dir, "reset.gen.go")
	return os.WriteFile(out, formatted, 0o644)
}

func writeResetMethod(buf *bytes.Buffer, named *types.Named, pkg *types.Package) {
	name := named.Obj().Name()
	fmt.Fprintf(buf, "func (s *%s) Reset() {\n", name)
	buf.WriteString("\tif s == nil {\n\t\treturn\n\t}\n\n")

	st, ok := named.Underlying().(*types.Struct)
	if !ok {
		buf.WriteString("}\n\n")
		return
	}

	for i := 0; i < st.NumFields(); i++ {
		field := st.Field(i)
		emitReset(buf, "s", field.Name(), field.Type(), 1, pkg)
	}

	buf.WriteString("}\n\n")
}

func emitReset(buf *bytes.Buffer, recv, name string, t types.Type, depth int, pkg *types.Package) {
	indent := strings.Repeat("\t", depth)
	qual := recv + "." + name

	switch u := types.Unalias(t).(type) {
	case *types.Basic:
		fmt.Fprintf(buf, "%s%s = %s\n", indent, qual, zeroLiteral(u))
	case *types.Slice:
		fmt.Fprintf(buf, "%s%s = %s[:0]\n", indent, qual, qual)
	case *types.Map:
		fmt.Fprintf(buf, "%sclear(%s)\n", indent, qual)
	case *types.Pointer:
		emitPointerReset(buf, qual, u.Elem(), depth, pkg)
	case *types.Struct:
		emitStructReset(buf, recv, name, u, depth)
	case *types.Named:
		if _, ok := u.Underlying().(*types.Struct); ok {
			emitNamedStructReset(buf, qual, u, depth)
			return
		}
		under := u.Underlying()
		switch ut := under.(type) {
		case *types.Slice:
			fmt.Fprintf(buf, "%s%s = %s[:0]\n", indent, qual, qual)
		case *types.Map:
			fmt.Fprintf(buf, "%sclear(%s)\n", indent, qual)
		case *types.Basic:
			fmt.Fprintf(buf, "%s%s = %s\n", indent, qual, zeroLiteral(ut))
		default:
			if hasReset(u) {
				fmt.Fprintf(buf, "%sif resetter, ok := any(%s).(interface{ Reset() }); ok {\n", indent, qual)
				fmt.Fprintf(buf, "%s\tresetter.Reset()\n", indent)
				fmt.Fprintf(buf, "%s}\n", indent)
			}
		}
	case *types.Interface:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, qual)
	default:
		fmt.Fprintf(buf, "%s%s = %s\n", indent, qual, zeroForType(t, pkg))
	}
}

func emitPointerReset(buf *bytes.Buffer, qual string, elem types.Type, depth int, pkg *types.Package) {
	indent := strings.Repeat("\t", depth)
	elem = types.Unalias(elem)

	switch e := elem.(type) {
	case *types.Basic:
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
		fmt.Fprintf(buf, "%s\t*%s = %s\n", indent, qual, zeroLiteral(e))
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Slice:
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
		fmt.Fprintf(buf, "%s\t*%s = (*%s)[:0]\n", indent, qual, qual)
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Map:
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
		fmt.Fprintf(buf, "%s\tclear(*%s)\n", indent, qual)
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Pointer:
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
		emitPointerReset(buf, "*"+qual, e.Elem(), depth+1, pkg)
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Struct, *types.Named:
		if isStructLike(elem) {
			fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
			fmt.Fprintf(buf, "%s\tif resetter, ok := any(%s).(interface{ Reset() }); ok {\n", indent, qual)
			fmt.Fprintf(buf, "%s\t\tresetter.Reset()\n", indent)
			fmt.Fprintf(buf, "%s\t}\n", indent)
			fmt.Fprintf(buf, "%s}\n", indent)
			return
		}
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
		fmt.Fprintf(buf, "%s\t*%s = %s\n", indent, qual, zeroValueExpr(elem, pkg))
		fmt.Fprintf(buf, "%s}\n", indent)
	default:
		if hasReset(types.NewPointer(elem)) || isStructLike(elem) {
			fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
			fmt.Fprintf(buf, "%s\tif resetter, ok := any(%s).(interface{ Reset() }); ok {\n", indent, qual)
			fmt.Fprintf(buf, "%s\t\tresetter.Reset()\n", indent)
			fmt.Fprintf(buf, "%s\t}\n", indent)
			fmt.Fprintf(buf, "%s}\n", indent)
		} else {
			fmt.Fprintf(buf, "%sif %s != nil {\n", indent, qual)
			fmt.Fprintf(buf, "%s\t*%s = %s\n", indent, qual, zeroValueExpr(elem, pkg))
			fmt.Fprintf(buf, "%s}\n", indent)
		}
	}
}

func isStructLike(t types.Type) bool {
	t = types.Unalias(t)
	if _, ok := t.(*types.Struct); ok {
		return true
	}
	if n, ok := t.(*types.Named); ok {
		_, ok := n.Underlying().(*types.Struct)
		return ok
	}
	return false
}

func zeroValueExpr(t types.Type, pkg *types.Package) string {
	t = types.Unalias(t)
	if n, ok := t.(*types.Named); ok {
		if n.Obj().Pkg() == pkg {
			return n.Obj().Name() + "{}"
		}
	}
	return types.TypeString(t, types.RelativeTo(pkg))
}

func emitStructReset(buf *bytes.Buffer, recv, name string, st *types.Struct, depth int) {
	qual := recv + "." + name
	if hasReset(types.NewPointer(st)) {
		indent := strings.Repeat("\t", depth)
		fmt.Fprintf(buf, "%sif resetter, ok := any(&%s).(interface{ Reset() }); ok {\n", indent, qual)
		fmt.Fprintf(buf, "%s\tresetter.Reset()\n", indent)
		fmt.Fprintf(buf, "%s}\n", indent)
		return
	}
	indent := strings.Repeat("\t", depth)
	fmt.Fprintf(buf, "%s%s = %s{}\n", indent, qual, typeString(st, nil))
}

func emitNamedStructReset(buf *bytes.Buffer, qual string, named *types.Named, depth int) {
	if hasReset(types.NewPointer(named)) {
		indent := strings.Repeat("\t", depth)
		fmt.Fprintf(buf, "%sif resetter, ok := any(%s).(interface{ Reset() }); ok {\n", indent, qual)
		fmt.Fprintf(buf, "%s\tresetter.Reset()\n", indent)
		fmt.Fprintf(buf, "%s}\n", indent)
		return
	}
	indent := strings.Repeat("\t", depth)
	fmt.Fprintf(buf, "%s%s = %s{}\n", indent, qual, named.Obj().Name())
}

func hasReset(t types.Type) bool {
	if t == nil {
		return false
	}
	mset := types.NewMethodSet(types.NewPointer(types.Unalias(t)))
	for i := 0; i < mset.Len(); i++ {
		m := mset.At(i)
		if m.Obj().Name() != "Reset" {
			continue
		}
		sig, ok := m.Type().(*types.Signature)
		if !ok {
			continue
		}
		if sig.Params().Len() == 0 && sig.Results().Len() == 0 {
			return true
		}
	}
	return false
}

func zeroLiteral(b *types.Basic) string {
	switch b.Kind() {
	case types.Bool:
		return "false"
	case types.String:
		return `""`
	case types.UnsafePointer:
		return "nil"
	default:
		return "0"
	}
}

func zeroForType(t types.Type, pkg *types.Package) string {
	switch u := types.Unalias(t).(type) {
	case *types.Basic:
		return zeroLiteral(u)
	case *types.Slice, *types.Map, *types.Pointer, *types.Interface, *types.Chan, *types.Signature:
		return "nil"
	default:
		return zeroValueExpr(t, pkg)
	}
}

func typeString(t types.Type, pkg *types.Package) string {
	if pkg == nil {
		return types.TypeString(t, nil)
	}
	return types.TypeString(t, types.RelativeTo(pkg))
}
