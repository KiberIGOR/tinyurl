// Package main реализует мультичекер статического анализа для проекта tinyurl.
//
// Инструмент собирает несколько анализаторов в один бинарный файл по принципу
// golang.org/x/tools/go/analysis/multichecker (см. материал курса «Статический анализ»).
// Запуск аналогичен go vet: указывается список пакетов, флаги включают и выключают
// отдельные проверки.
//
// # Сборка и запуск
//
// Собрать бинарный файл из корня модуля:
//
//	go build -o staticlint ./cmd/staticlint
//
// Проверить весь проект:
//
//	go run ./cmd/staticlint ./...
//
//	./staticlint ./...
//
// Проверить один пакет:
//
//	./staticlint ./internal/handler
//
// Справка по флагам и списку анализаторов:
//
//	./staticlint -help
//
// Справка по конкретному анализатору:
//
//	./staticlint help printf
//	./staticlint help osexit
//	./staticlint help SA4006
//
// Запустить только выбранные проверки:
//
//	./staticlint -printf -osexit ./...
//
// Отключить отдельные проверки:
//
//	./staticlint -shadow=false ./...
//
// # Состав мультичекера
//
//  1. Стандартные анализаторы пакета golang.org/x/tools/go/analysis/passes
//     (аналог расширенного go vet). Не подключаются служебные пакеты inspect,
//     ctrlflow, buildssa и демонстрационные findcall/pkgfact — они не являются
//     самостоятельными проверками, а предоставляют факты другим анализаторам.
//  2. Все анализаторы класса SA пакета honnef.co/go/tools/staticcheck
//     (https://staticcheck.dev/docs/checks/#sa).
//  3. Анализатор ST1012 класса ST (stylecheck) — проверка имён переменных ошибок.
//  4. Публичные анализаторы bodyclose и ineffassign.
//  5. Собственный анализатор osexit: запрет прямого вызова os.Exit в func main
//     пакета main.
//
// # Стандартные анализаторы passes
//
//   - appends — некорректное использование append (например, пересечение срезов).
//   - asmdecl — несоответствие прототипов Go и сборочных файлов.
//   - assign — бесполезные присваивания вида x = x.
//   - atomic — некорректное использование sync/atomic.
//   - atomicalign — невыровненные 64-битные atomic-поля на 32-битных платформах.
//   - bools — распространённые ошибки в булевых выражениях.
//   - buildtag — некорректные build-теги.
//   - cgocall — нарушения правил передачи указателей в cgo.
//   - composite — незаданные ключи в композитных литералах нелокальных структур.
//   - copylock — копирование значений с locks (например, sync.Mutex).
//   - deepequalerrors — сравнение ошибок через reflect.DeepEqual.
//   - defers — подозрительные аргументы отложенных вызовов.
//   - directive — ошибки в директивах //go:debug и подобных.
//   - errorsas — некорректные аргументы errors.As.
//   - framepointer — сборка, ломающая frame pointer на amd64.
//   - hostport — сборка адреса через fmt.Sprintf("%s:%d") вместо net.JoinHostPort.
//   - httpresponse — HTTP-ответ не закрыт или используется после ошибки.
//   - ifaceassert — невозможные приведения интерфейсов.
//   - loopclosure — захват переменной цикла в горутине/отложенном вызове.
//   - lostcancel — контекст с cancel создан, но cancel не вызывается.
//   - nilfunc — сравнение функции с nil.
//   - nilness — избыточные или ошибочные проверки на nil.
//   - printf — несоответствие форматной строки и аргументов.
//   - reflectvaluecompare — сравнение reflect.Value напрямую вместо Interface().
//   - shadow — затенение переменных из внешнего блока.
//   - shift — сдвиги, превышающие размер целого.
//   - sigchanyzer — send в небуферизованный канал os.Signal.
//   - slog — некорректные пары ключ-значение в log/slog.
//   - sortslice — sort.Slice с функцией сравнения неверного типа.
//   - stdmethods — неверные сигнатуры стандартных методов (WriteTo, Error и т.д.).
//   - stdversion — использование символов стандартной библиотеки, недоступных в go-версии модуля.
//   - stringintconv — подозрительное преобразование int в string.
//   - structtag — некорректные теги структур.
//   - testinggoroutine — вызов t.Fatal из посторонней горутины.
//   - tests — неверные сигнатуры Test/Benchmark/Fuzz/Example.
//   - timeformat — ошибочный формат времени 2006-02-01 вместо 2006-01-02.
//   - unmarshal — передача не-указателя в json.Unmarshal и аналоги.
//   - unreachable — недостижимый код.
//   - unsafeptr — недопустимое преобразование uintptr в unsafe.Pointer.
//   - unusedresult — игнорирование результата функций вроде fmt.Errorf, errors.New.
//   - unusedwrite — записи в переменные/поля, которые никогда не читаются.
//   - waitgroup — некорректное использование sync.WaitGroup (Add внутри горутины и т.п.).
//
// # Анализаторы staticcheck класса SA
//
// Подключаются все проверки с префиксом SA. Группы по номерам:
//
//   - SA1xxx — ошибки использования стандартной библиотеки (время, regexp, HTTP, SQL и др.).
//   - SA2xxx — ошибки конкурентности (плохое использование mutex, WaitGroup, каналов).
//   - SA3xxx — ошибки тестов.
//   - SA4xxx — бесполезный или некорректный код (неиспользуемые значения, тождественные ветки).
//   - SA5xxx — логические ошибки и бесконечные циклы, defer в неправильном месте.
//   - SA6xxx — производительность (неэффективные преобразования, лишние аллокации).
//   - SA9xxx — сомнительные конструкции, которые почти наверняка ошибочны.
//
// Полный список и примеры: https://staticcheck.dev/docs/checks/#sa
// Справка по конкретному правилу: staticlint help SA4010
//
// # Анализатор других классов staticcheck
//
//   - ST1012 (stylecheck) — переменные ошибок в публичном API должны называться
//     errXxx или ErrXxx. Класс ST — стилистические проверки; остальные классы
//     staticcheck: S (упрощения) и QF (автоисправления).
//
// # Публичные анализаторы
//
//   - bodyclose (github.com/timakin/bodyclose) — тело HTTP-ответа (*http.Response).Body
//     должно быть закрыто, иначе возможна утечка соединений.
//   - ineffassign (github.com/gordonklaus/ineffassign) — присваивания, результат
//     которых никогда не используется.
//
// # Собственный анализатор osexit
//
// Запрещает прямой вызов os.Exit в функции main пакета main. Такой вызов
// пропускает отложенные функции (defer) и затрудняет тестирование точки входа.
// Косвенный выход через log.Fatal не считается прямым вызовом и не диагностируется.
//
// Диагностируется только конструкция вида os.Exit(...) внутри func main()
// пакета main, в том числе при переименованном импорте (import stdos "os").
// Вызовы os.Exit в других функциях того же пакета не запрещены.
// Синтетические пакеты *.test и сгенерированные файлы (в том числе testmain)
// пропускаются, чтобы не ругаться на служебный код go test.
package main
